import '../schema/beak_schema_ir.dart';
import 'definition_model.dart';
import 'handler_emitter.dart';

/// The `<Prefix>Handlers` aggregate: one required handler per model whose
/// definition opens custom code, the write bindings and the row scopes.
String emitHandlerAggregate(
  String prefix,
  HandlerImports imports,
  List<(BeakGeneratedModel, DefinitionClass)> models,
  List<(BeakGeneratedModel, DefinitionClass)> handled,
) {
  final writable = [
    for (final entry in models)
      if (entry.$2.write != null) entry,
  ];
  final files = [
    for (final (_, definition) in handled)
      '${snakeOf(definition.name)}_handler.dart',
  ]..sort();
  final uris = <String, String>{
    'package:beak_backend/beak_backend.dart': '',
    'package:beak_serverpod_server/beak_serverpod_server.dart': '',
    if (writable.isNotEmpty || handled.isNotEmpty)
      'package:${imports.definitions}/${imports.definitions}.dart': ' as admin',
    for (final file in files) imports.uriOf(file): '',
  };
  final buffer = StringBuffer()
    ..writeln('// GENERATED BY beak generate — DO NOT EDIT.')
    ..writeln();
  final sorted = uris.keys.toList()
    ..sort((a, b) {
      final relative = (a.startsWith('package:') ? 0 : 1).compareTo(
        b.startsWith('package:') ? 0 : 1,
      );
      return relative != 0 ? relative : a.compareTo(b);
    });
  for (final uri in sorted) {
    buffer.writeln("import '$uri'${uris[uri]};");
  }
  buffer.writeln();
  for (final file in files) {
    buffer.writeln("export '${imports.uriOf(file)}';");
  }
  if (files.isNotEmpty) buffer.writeln();
  buffer
    ..writeln('/// The server handlers of the admin models.')
    ..writeln('///')
    ..writeln(
      '/// Every model whose definition opens custom code has a required '
      'handler,',
    )
    ..writeln('/// so a missing one does not compile; every other model is')
    ..writeln('/// saved the stock way.')
    ..writeln(
      'final class ${prefix}Handlers implements BeakServerpodHandlers {',
    )
    ..writeln('  /// Creates the handlers.');
  if (handled.isEmpty) {
    buffer.writeln('  const ${prefix}Handlers();');
  } else {
    buffer.writeln('  const ${prefix}Handlers({');
    for (final (_, definition) in handled) {
      buffer.writeln('    required this.${camelOf(definition.name)},');
    }
    buffer.writeln('  });');
  }
  for (final (_, definition) in handled) {
    buffer
      ..writeln()
      ..writeln('  /// Runs the custom code of ${definition.name}.')
      ..writeln(
        '  final ${definition.name}Handler ${camelOf(definition.name)};',
      );
  }
  buffer
    ..writeln()
    ..writeln('  @override');
  if (writable.isEmpty) {
    buffer.writeln('  BeakWriteBindings<Enum>? get writes => null;');
  } else {
    final stock = [
      for (final (_, definition) in writable)
        if (!definition.needsHandler || !_writesThroughHandler(definition))
          'admin.${prefix}Write.${definition.write}',
    ];
    buffer
      ..writeln('  BeakWriteBindings<admin.${prefix}Write> get writes =>')
      ..writeln('      BeakWriteBindings((binding) => switch (binding) {');
    for (final (_, definition) in writable) {
      if (!definition.needsHandler || !_writesThroughHandler(definition)) {
        continue;
      }
      buffer.writeln(
        '        admin.${prefix}Write.${definition.write} => '
        '${camelOf(definition.name)}.writes,',
      );
    }
    if (stock.isNotEmpty) {
      buffer.writeln(
        '        ${stock.join(' || ')} => const BeakWriteHandler.stock(),',
      );
    }
    buffer.writeln('      });');
  }
  final scoped = [
    for (final entry in handled)
      if (entry.$2.list == DefinitionHandling.custom) entry,
  ];
  buffer
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  List<BeakRowScope> get scopes => ${scoped.isEmpty ? 'const ' : ''}[',
    );
  for (final (model, definition) in scoped) {
    buffer.writeln(
      '    BeakRowScope(const admin.${model.schema.modelClass}(), '
      '${camelOf(definition.name)}.scope),',
    );
  }
  buffer
    ..writeln('  ];')
    ..writeln('}');
  return BeakEmitters.format(buffer.toString());
}

bool _writesThroughHandler(DefinitionClass definition) =>
    definition.create.needsHandler ||
    definition.update.needsHandler ||
    definition.delete == DefinitionHandling.custom ||
    definition.commands.isNotEmpty;
