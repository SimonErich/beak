/// The packages the generated server handlers import.
final class HandlerImports {
  /// Creates the import set.
  const HandlerImports({
    required this.definitions,
    required this.server,
    this.folder,
  });

  /// The definitions package name (imported `as admin`).
  final String definitions;

  /// The Serverpod server package name (its protocol is imported
  /// `as protocol`).
  final String server;

  /// The handler folder under the server's `lib/` (`src/admin`), so the
  /// aggregate imports the handler libraries by package URI; `null` keeps
  /// them relative.
  final String? folder;

  /// The URI the aggregate imports [file] by.
  String uriOf(String file) =>
      folder == null ? file : 'package:$server/$folder/$file';
}

/// The server handler files `beak generate` writes into `generate.handlers`,
/// keyed by file name.
///
/// One library per model whose definition opens custom code holds its typed
/// write, its typed values and an abstract base class whose methods are the
/// custom operations; the aggregate requires one implementation of each.
Map<String, String> emitServerpodHandlers({
  required String prefix,
  required HandlerImports imports,
  required List<(BeakGeneratedModel, DefinitionClass)> models,
  required List<BeakGeneratedInput> inputs,
}) {
  final files = <String, String>{};
  final handled = [
    for (final entry in models)
      if (entry.$2.needsHandler) entry,
  ];
  for (final (model, definition) in handled) {
    files['${snakeOf(definition.name)}_handler.dart'] = _handlerLibrary(
      model,
      definition,
      imports,
      inputs,
    );
  }
  files['${snakeOf(prefix)}_handlers.dart'] = emitHandlerAggregate(
    prefix,
    imports,
    models,
    handled,
  );
  return files;
}

/// `ProductCategory` -> `product_category`.
String snakeOf(String name) => name
    .replaceAllMapped(
      RegExp(r'([a-z0-9])([A-Z])'),
      (match) => '${match[1]}_${match[2]}',
    )
    .toLowerCase();

/// `ProductCategory` -> `productCategory`.
String camelOf(String name) => '${name[0].toLowerCase()}${name.substring(1)}';

String _handlerLibrary(
  BeakGeneratedModel model,
  DefinitionClass definition,
  HandlerImports imports,
  List<BeakGeneratedInput> inputs,
) {
  final commandInputs = [
    for (final name in definition.commandInputs.values.toSet())
      inputs.firstWhere((input) => input.schema.className == name),
  ];
  final schemas = [
    model.schema,
    for (final input in commandInputs) input.schema,
  ];
  final buffer = StringBuffer()
    ..writeln('// GENERATED BY beak generate — DO NOT EDIT.')
    ..writeln()
    ..writeln("import 'dart:async';")
    ..writeln()
    ..writeln("import 'package:beak_backend/beak_backend.dart';")
    ..writeln("import 'package:beak_core/beak_core.dart';")
    ..writeln(
      "import 'package:beak_serverpod_server/beak_serverpod_server.dart';",
    )
    ..writeln(
      "import 'package:${imports.definitions}/${imports.definitions}.dart'",
    )
    ..writeln('    as admin;');
  if (schemas.any(usesProtocol)) {
    buffer.writeln(
      "import 'package:${imports.server}/src/generated/protocol.dart' "
      'as protocol;',
    );
  }
  if (schemas.any(usesUuid)) {
    buffer.writeln("import 'package:serverpod/serverpod.dart' show UuidValue;");
  }
  buffer.writeln();
  writeTypedWrite(buffer, model.schema);
  writeTypedValues(buffer, model.schema);
  for (final input in commandInputs) {
    writeTypedCommandWrite(buffer, input.schema);
    writeTypedValues(buffer, input.schema);
  }
  writeHandlerBase(
    buffer,
    model,
    definition,
    commandWrites: {
      for (final entry in definition.commandInputs.entries)
        entry.key: '${entry.value}Write',
    },
  );
  return BeakEmitters.format(buffer.toString());
}
