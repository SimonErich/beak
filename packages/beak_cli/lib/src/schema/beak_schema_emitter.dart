import '../project/beak_emitters.dart';
import 'beak_schema_ir.dart';
import 'beak_schema_reader.dart';

/// Emits the Dart a schema class stands for.
///
/// One declaration becomes five artefacts, each of which was previously
/// hand-written and had to be kept in step by hand: the typed column
/// constants and their `values` list, the relationship constants on *both*
/// sides, the `BeakModel`, and a typed record view so reading a field no
/// longer means `record[key]?.raw` and a switch.
///
/// The output is deliberately dull — declarations and one-line delegations
/// into `beak_core`, never logic. That is what lets it pass `--fatal-infos`
/// on its own merits and keeps the emitter testable as string comparison.
abstract final class BeakSchemaEmitter {
  /// The part file [schema] generates, as Dart source.
  ///
  /// [all] supplies every schema in the project, so relationships can resolve
  /// the table and display column of the class on the far side, and so
  /// inverse relationships declared elsewhere land here.
  static String emit(BeakSchemaIr schema, List<BeakSchemaIr> all) {
    final byClass = {for (final other in all) other.className: other};
    final buffer = StringBuffer()
      ..writeln('// GENERATED BY `beak prepare` — DO NOT EDIT.')
      ..writeln('// Regenerated from the @Resource class in this library.')
      ..writeln()
      ..writeln("part of '${_fileNameOf(schema.libraryPath)}';")
      ..writeln();

    _writeColumns(buffer, schema);
    _writeRelations(buffer, schema, byClass, all);
    _writeFields(buffer, schema, byClass);
    _writeModel(buffer, schema, all);
    _writeDraft(buffer, schema, byClass);
    _writeRecord(buffer, schema, byClass);
    // Formatted here rather than by the caller, so any consumer of the
    // emitter gets source that `dart format --set-exit-if-changed` accepts.
    return BeakEmitters.format(buffer.toString());
  }

  /// The `part` file name for a schema declared in [libraryPath].
  static String partFileNameOf(String libraryPath) =>
      '${_fileNameOf(libraryPath).replaceAll('.dart', '')}.beak.dart';

  /// The project-relative path [schema]'s part file is written to.
  ///
  /// One derivation, used by `beak prepare` to write the file and by
  /// `beak doctor` to notice it has gone stale — two answers here would mean
  /// the generator and the check disagreeing about which file they mean.
  static String partPathOf(BeakSchemaIr schema) {
    final int slash = schema.libraryPath.lastIndexOf('/');
    final String directory = slash < 0
        ? ''
        : schema.libraryPath.substring(0, slash + 1);
    return 'lib/$directory${partFileNameOf(schema.libraryPath)}';
  }

  static void _writeColumns(StringBuffer buffer, BeakSchemaIr schema) {
    buffer
      ..writeln('/// Typed column constants of the ${schema.table} resource.')
      ..writeln('abstract final class ${schema.columnsClass} {');
    for (final column in schema.columns) {
      _writeDoc(buffer, column.docComment ?? column.label, indent: '  ');
      buffer
        ..writeln(
          '  static const ${_columnTypeOf(column)} '
          '${column.fieldName} = ${_columnTypeOf(column)}(',
        )
        ..writeln("    key: '${column.columnKey}',")
        ..writeln("    label: '${_escape(column.label)}',");
      for (final entry in _columnArgumentsOf(column, schema).entries) {
        buffer.writeln('    ${entry.key}: ${entry.value},');
      }
      buffer.writeln('  );');
      buffer.writeln();
    }
    buffer
      ..writeln('  /// Every column, in declaration order.')
      ..writeln('  static const List<BeakColumn> values = [')
      ..writeln('    ${schema.columns.map((c) => c.fieldName).join(', ')},')
      ..writeln('  ];')
      ..writeln('}')
      ..writeln();
  }

  static void _writeRelations(
    StringBuffer buffer,
    BeakSchemaIr schema,
    Map<String, BeakSchemaIr> byClass,
    List<BeakSchemaIr> all,
  ) {
    final inverses = _inversesTargeting(schema, all);
    if (schema.relations.isEmpty && inverses.isEmpty) {
      return;
    }
    buffer
      ..writeln(
        '/// Typed relationship constants of the ${schema.table} '
        'resource.',
      )
      ..writeln('abstract final class ${schema.relationsClass} {');

    for (final relation in schema.relations) {
      final BeakSchemaIr? related = byClass[relation.relatedSchema];
      if (related == null) {
        continue;
      }
      _writeDoc(buffer, relation.docComment ?? relation.label, indent: '  ');
      _writeRelationConstant(
        buffer,
        name: relation.fieldName,
        type: relation.kind.relationType,
        key: relation.key,
        label: relation.label,
        related: related,
        arguments: _relationArgumentsOf(relation, schema, related),
      );
    }

    for (final (owner, relation) in _emittedInverses(schema, all)) {
      final String name = _inverseNameOf(owner, relation);
      _writeDoc(
        buffer,
        'The ${owner.table} on the other side of '
        '[${owner.relationsClass}.${relation.fieldName}].',
        indent: '  ',
      );
      _writeRelationConstant(
        buffer,
        name: name,
        type: _inverseKindOf(relation.kind).relationType,
        key: name,
        label: titleCaseOf(name),
        related: owner,
        arguments: _inverseArgumentsOf(relation, schema, owner),
      );
    }

    buffer
      ..writeln('}')
      ..writeln();
  }

  /// The inverse relationships this schema emits a constant for.
  ///
  /// An explicit declaration always wins over the inverse that would have
  /// been synthesized for it: `beak introspect` writes both sides of a
  /// relationship, and two identical constants is a compile error rather
  /// than a redundancy the user can ignore.
  ///
  /// Shared by the relations class and the model's `relationships` list —
  /// they were allowed to disagree once, and every synthesized inverse was
  /// generated and then registered nowhere, so a `Category` show page had no
  /// products tab and `BeakBlueprint` could not see the foreign key.
  static List<(BeakSchemaIr, BeakRelationIr)> _emittedInverses(
    BeakSchemaIr schema,
    List<BeakSchemaIr> all,
  ) {
    final taken = {for (final relation in schema.relations) relation.fieldName};
    return <(BeakSchemaIr, BeakRelationIr)>[
      for (final (owner, relation) in _inversesTargeting(schema, all))
        if (taken.add(_inverseNameOf(owner, relation)) &&
            !schema.relations.any((r) => r.relatedSchema == owner.className))
          (owner, relation),
    ];
  }

  static void _writeRelationConstant(
    StringBuffer buffer, {
    required String name,
    required String type,
    required String key,
    required String label,
    required BeakSchemaIr related,
    required Map<String, String> arguments,
  }) {
    buffer
      ..writeln('  static const $type $name = $type(')
      ..writeln("    key: '$key',")
      ..writeln("    label: '${_escape(label)}',")
      ..writeln("    relatedTable: '${related.table}',")
      ..writeln("    displayColumnKey: '${related.displayColumnKey}',");
    for (final entry in arguments.entries) {
      buffer.writeln('    ${entry.key}: ${entry.value},');
    }
    buffer
      ..writeln('  );')
      ..writeln();
  }

  static void _writeModel(
    StringBuffer buffer,
    BeakSchemaIr schema,
    List<BeakSchemaIr> all,
  ) {
    _writeDoc(buffer, schema.docComment ?? 'The ${schema.table} resource.');
    buffer
      ..writeln('final class ${schema.modelClass} extends BeakModel {')
      ..writeln('  /// Creates the ${schema.table} model.')
      ..writeln('  const ${schema.modelClass}();')
      ..writeln()
      ..writeln(
        '  /// Typed field and relation references, including reserved names.',
      )
      ..writeln(
        '  static const ${schema.className}Fields fields = ${schema.className}Fields();',
      );
    for (final field in _fieldNames(schema)) {
      if (_modelReserved.contains(field)) continue;
      buffer
        ..writeln('  /// Typed reference to [$field] in this model.')
        ..writeln('  static final $field = fields.$field;');
    }
    buffer
      ..writeln('  /// Declarative source for record choices.')
      ..writeln(
        '  static BeakOptionQuery options({BeakFilter? filter}) => BeakOptionQuery(model: const ${schema.modelClass}(), query: const ${schema.modelClass}().query(filter: filter));',
      )
      ..writeln('  /// Searches the model display and searchable columns.')
      ..writeln(
        '  static BeakOptionQuery search(String term, {BeakFilter? filter}) => BeakOptionQuery(model: const ${schema.modelClass}(), query: const ${schema.modelClass}().query(filter: filter, search: BeakSearch(term, const [${_modelSearchKeys(schema)}])));',
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln("  String get table => '${schema.table}';")
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        "  String get displayColumnKey => '${schema.displayColumnKey}';",
      )
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  List<BeakColumn> get columns => ${schema.columnsClass}.values;',
      );
    if (schema.hasValidationRules) {
      buffer
        ..writeln('  @override')
        ..writeln(
          '  List<BeakRecordRule> get validationRules => ${schema.className}.validationRules;',
        );
    }
    if (schema.hasBehavior) {
      buffer
        ..writeln('  @override')
        ..writeln(
          '  BeakModelBehavior get behavior => ${schema.className}.behavior;',
        );
    }
    if (schema.hasPermissions) {
      buffer
        ..writeln('  @override')
        ..writeln(
          '  BeakPermissions get permissions => ${schema.className}.permissions;',
        );
    }
    if (schema.hasCapabilities) {
      buffer
        ..writeln('  @override')
        ..writeln(
          '  Set<BeakOperation> get capabilities => ${schema.className}.capabilities;',
        );
    }
    if (schema.relations.isNotEmpty) {
      buffer
        ..writeln('  @override')
        ..writeln(
          '  List<BeakModel> get relatedModels => const [${schema.relations.map((r) => '${r.relatedSchema}Model()').toSet().join(', ')}];',
        );
    }
    // Both the declared relationships and the synthesized inverses: a
    // constant the relations class emits and the model does not register is
    // dead code the panel can never reach.
    final inverses = _emittedInverses(schema, all);
    if (schema.relations.isNotEmpty || inverses.isNotEmpty) {
      buffer
        ..writeln()
        ..writeln('  @override')
        ..writeln('  List<BeakRelationship> get relationships => const [');
      for (final relation in schema.relations) {
        buffer.writeln('    ${schema.relationsClass}.${relation.fieldName},');
      }
      for (final (owner, relation) in inverses) {
        buffer.writeln(
          '    ${schema.relationsClass}.${_inverseNameOf(owner, relation)},',
        );
      }
      buffer.writeln('  ];');
    }
    if (schema.softDeletes) {
      buffer
        ..writeln()
        ..writeln('  @override')
        ..writeln('  bool get softDeletes => true;');
    }
    buffer
      ..writeln()
      ..writeln('  @override')
      ..writeln('  List<Enum> get formSlots => ${_slotEnumOf(schema)}.values;')
      ..writeln('}')
      ..writeln();
    _writeFormSlots(buffer, schema);
  }

  static const _modelReserved = {
    'fields',
    'options',
    'search',
    'table',
    'displayColumnKey',
    'columns',
    'permissions',
    'validationRules',
    'behavior',
    'capabilities',
    'dataSource',
    'createModel',
    'editModel',
    'relationships',
    'relatedModels',
    'softDeletes',
    'formSlots',
    'primaryKey',
    'ref',
    'query',
    'count',
    'sum',
    'avg',
    'primaryKeyOf',
    'columnsFor',
    'columnByKey',
    'relationshipByKey',
    'toString',
    'noSuchMethod',
    'hashCode',
    'runtimeType',
  };

  static const _relationReserved = {
    'fields',
    'model',
    'path',
    'isRequired',
    'key',
    'label',
    'qualifiedKey',
    'readFrom',
    'ownerRecord',
    'relation',
    'target',
    'eq',
    'equalsId',
    'matches',
    'options',
    'hashCode',
    'runtimeType',
    'toString',
    'noSuchMethod',
  };

  static Iterable<String> _fieldNames(BeakSchemaIr schema) sync* {
    yield* schema.columns.map((column) => column.fieldName);
    yield* schema.relations.map((relation) => relation.fieldName);
  }

  static String _modelSearchKeys(BeakSchemaIr schema) => {
    schema.displayColumnKey,
    for (final column in schema.columns)
      if (column.arguments['searchable'] == 'true' &&
          !(column.arguments['semantic']?.contains('BeakSemantic.password(') ??
              false))
        column.columnKey,
  }.map((key) => "'$key'").join(', ');

  static bool _isMany(BeakRelationIr relation) =>
      relation.kind == BeakRelationKind.hasMany ||
      relation.kind == BeakRelationKind.belongsToMany;

  static String _relationFieldType(BeakRelationIr relation) => _isMany(relation)
      ? 'BeakToManyField'
      : '${relation.relatedSchema}ToOneField';

  static void _writeFields(
    StringBuffer buffer,
    BeakSchemaIr schema,
    Map<String, BeakSchemaIr> byClass,
  ) {
    buffer
      ..writeln('/// Typed configuration references for ${schema.className}.')
      ..writeln('final class ${schema.className}Fields {')
      ..writeln(
        '  /// Creates the fields of ${schema.className}, rooted at its own '
        'model.',
      )
      // The second constructor takes its two values positionally on purpose:
      // a named `model` feeding `_model` is what `prefer_initializing_formals`
      // reports from Dart 3.12, yet `this._model` as a named parameter is a
      // syntax error before it, and generated code has to be clean in both.
      ..writeln(
        '  const ${schema.className}Fields() : '
        '_model = const ${schema.modelClass}(), _path = const [];',
      )
      ..writeln(
        '  /// Creates fields rooted at [model] and reached through [path].',
      )
      ..writeln(
        '  const ${schema.className}Fields.via(this._model, this._path);',
      )
      ..writeln('  final BeakModel _model;')
      ..writeln('  final List<BeakRelationship> _path;');
    for (final column in schema.columns) {
      buffer
        ..writeln('  /// ${column.label}.')
        ..writeln(
          '  BeakScalarField<${column.valueType}> get ${column.fieldName} => BeakScalarField<${column.valueType}>(model: _model, column: ${schema.columnsClass}.${column.fieldName}, path: _path, isRequired: ${column.isRequired});',
        );
    }
    for (final relation in schema.relations) {
      final related = byClass[relation.relatedSchema];
      if (related == null) continue;
      buffer
        ..writeln('  /// ${relation.label}.')
        ..writeln(
          '  ${_relationFieldType(relation)} get ${relation.fieldName} => ${_relationFieldType(relation)}(model: _model, relation: ${schema.relationsClass}.${relation.fieldName}, ${_isMany(relation) ? 'target: const ${related.modelClass}(),' : ''} path: _path, isRequired: ${relation.isRequired});',
        );
    }
    buffer
      ..writeln('}')
      ..writeln(
        '/// A to-one path to ${schema.className}, retaining its root owner.',
      )
      ..writeln(
        'final class ${schema.className}ToOneField extends BeakToOneField {',
      )
      ..writeln('  /// Creates a typed relationship path.')
      ..writeln(
        '  const ${schema.className}ToOneField({required super.model, required super.relation, super.path, super.isRequired}) : super(target: const ${schema.modelClass}());',
      )
      ..writeln(
        '  /// Every target field, including names reserved by the path API.',
      )
      ..writeln(
        '  ${schema.className}Fields get fields => ${schema.className}Fields.via(model, [...path, relation]);',
      );
    for (final column in schema.columns) {
      if (_relationReserved.contains(column.fieldName)) continue;
      buffer
        ..writeln('  /// ${column.label}.')
        ..writeln(
          '  BeakScalarField<${column.valueType}> get ${column.fieldName} => fields.${column.fieldName};',
        );
    }
    for (final relation in schema.relations) {
      if (_relationReserved.contains(relation.fieldName)) continue;
      buffer
        ..writeln('  /// ${relation.label}.')
        ..writeln(
          '  ${_relationFieldType(relation)} get ${relation.fieldName} => fields.${relation.fieldName};',
        );
    }
    buffer.writeln('}');
  }

  static void _writeDraft(
    StringBuffer buffer,
    BeakSchemaIr schema,
    Map<String, BeakSchemaIr> byClass,
  ) {
    buffer
      ..writeln(
        '/// A live, nullable view of an incomplete ${schema.className} draft.',
      )
      ..writeln('final class ${schema.className}Draft {')
      ..writeln(
        '  /// Reads values through the session so dependencies stay observable.',
      )
      ..writeln('  const ${schema.className}Draft(this._reader);')
      ..writeln('  final BeakDraftReader _reader;');
    for (final column in schema.columns) {
      buffer
        ..writeln('  /// ${column.label}, or null while incomplete.')
        ..writeln(
          '  ${column.valueType}? get ${column.fieldName} => _reader.read(${schema.modelClass}.fields.${column.fieldName});',
        );
    }
    for (final relation in schema.relations) {
      final related = byClass[relation.relatedSchema];
      if (related == null) continue;
      buffer.writeln('  /// The selected ${relation.label.toLowerCase()}.');
      if (_isMany(relation)) {
        buffer.writeln(
          '  List<${related.recordClass}> get ${relation.fieldName} => [for (final row in _reader.read(${schema.modelClass}.fields.${relation.fieldName}) ?? const <BeakRecord>[]) ${related.recordClass}.of(row)];',
        );
      } else {
        buffer.writeln(
          '  ${related.recordClass}? get ${relation.fieldName} => switch (_reader.read(${schema.modelClass}.fields.${relation.fieldName})) { final BeakRecord record => ${related.recordClass}.of(record), null => null };',
        );
      }
    }
    buffer
      ..writeln('}')
      ..writeln('/// Typed access to live ${schema.className} form values.')
      ..writeln('extension ${schema.className}DraftAccess on BeakDraftReader {')
      ..writeln('  /// Nullable values backed by this tracked reader.')
      ..writeln(
        '  ${schema.className}Draft get as${schema.className} => ${schema.className}Draft(this);',
      )
      ..writeln('}');
  }

  /// The private enum a model's forms claim field slots from.
  ///
  /// Auto forms key fields by an enum; Beak's columns are runtime values, so
  /// a form takes one enum value per field it registers. Sizing the pool per
  /// model is what removes the ceiling a shared pool imposes: a table with 60
  /// columns gets 60 slots, and nobody has to know that is how it works.
  ///
  /// One slot per column plus one per relationship is an upper bound on what
  /// `defineFields` can claim, and an unused enum value costs nothing.
  static void _writeFormSlots(StringBuffer buffer, BeakSchemaIr schema) {
    final int count = schema.columns.length + schema.relations.length;
    buffer
      ..writeln('/// Form-field slots of ${schema.modelClass}.')
      ..writeln('///')
      ..writeln('/// An implementation bridge, never shown and never stored:')
      ..writeln('/// auto forms key their fields by an enum, and this supplies')
      ..writeln(
        '/// one value per field ${schema.className} can put on a form.',
      )
      ..writeln('enum ${_slotEnumOf(schema)} {')
      ..writeln('  /// Bridge slots.')
      ..writeln('  ${List.generate(count, _slotName).join(', ')},')
      ..writeln('}')
      ..writeln();
  }

  /// `_ProductFormSlot`, private to the model's library.
  static String _slotEnumOf(BeakSchemaIr schema) =>
      '_${schema.modelClass}FormSlot';

  /// `s0`, `s1`, … — deliberately meaningless, because they are.
  static String _slotName(int index) => 's$index';

  static void _writeRecord(
    StringBuffer buffer,
    BeakSchemaIr schema,
    Map<String, BeakSchemaIr> byClass,
  ) {
    buffer
      ..writeln('/// A typed, zero-cost view over a ${schema.table} record.')
      ..writeln('///')
      ..writeln('/// Reads fields through their own columns, so a value comes')
      ..writeln('/// back as its declared Dart type rather than an `Object?`')
      ..writeln('/// the caller has to pattern-match.')
      ..writeln(
        'extension type const ${schema.recordClass}._(BeakRecord record) {',
      )
      ..writeln('  /// Views [record] as a ${schema.table} row.')
      ..writeln(
        '  const ${schema.recordClass}.of(BeakRecord record) : this._(record);',
      )
      ..writeln();

    for (final column in schema.columns) {
      final String type = column.valueType;
      final bool required = column.isRequired;
      _writeDoc(buffer, column.docComment ?? column.label, indent: '  ');
      buffer
        ..writeln('  $type${required ? '' : '?'} get ${column.fieldName} =>')
        ..writeln(
          '      ${column.declaredValueType == null ? schema.columnsClass : '${schema.modelClass}.fields'}.${column.fieldName}'
          '.${required ? 'require' : 'readFrom'}(record);',
        )
        ..writeln();
    }

    for (final relation in schema.relations) {
      final BeakSchemaIr? related = byClass[relation.relatedSchema];
      if (related == null) {
        continue;
      }
      final bool many =
          relation.kind == BeakRelationKind.hasMany ||
          relation.kind == BeakRelationKind.belongsToMany;
      _writeDoc(
        buffer,
        'The eager-loaded ${relation.label.toLowerCase()}'
        '${many ? '' : ', or null when unloaded or unset'}.',
        indent: '  ',
      );
      if (many) {
        buffer
          ..writeln(
            '  List<${related.recordClass}> get ${relation.fieldName} => [',
          )
          // The element type must be spelled out: a bare `const []` is
          // List<dynamic>, which makes `row` dynamic and fails strict-casts.
          ..writeln(
            "    for (final row in record.relations['${relation.key}'] ?? "
            'const <BeakRecord>[])',
          )
          ..writeln('      ${related.recordClass}.of(row),')
          ..writeln('  ];');
      } else {
        buffer
          ..writeln('  ${related.recordClass}? get ${relation.fieldName} =>')
          ..writeln("      switch (record.relations['${relation.key}']) {")
          ..writeln(
            '        [final BeakRecord first, ...] => '
            '${related.recordClass}.of(first),',
          )
          ..writeln('        _ => null,')
          ..writeln('      };');
      }
      buffer.writeln();
    }

    buffer
      ..writeln('}')
      ..writeln()
      ..writeln('/// Views any record as a ${schema.table} row.')
      ..writeln('extension ${schema.className}RecordAccess on BeakRecord {')
      ..writeln('  /// This record, typed as a ${schema.table} row.')
      ..writeln(
        '  ${schema.recordClass} get as${schema.className} => '
        '${schema.recordClass}.of(this);',
      )
      ..writeln('}');
  }

  /// Whether [kind] is an upload column, which needs a storage path.
  static bool _isUploadKind(BeakColumnKind kind) =>
      kind == BeakColumnKind.image || kind == BeakColumnKind.file;

  /// The column constructor, with its type argument for an enum column.
  static String _columnTypeOf(BeakColumnIr column) =>
      column.kind == BeakColumnKind.enumeration
      ? 'BeakEnumColumn<${column.enumTypeName}>'
      : column.kind.columnType;

  /// The named arguments a column constant carries, rules included.
  static Map<String, String> _columnArgumentsOf(
    BeakColumnIr column,
    BeakSchemaIr schema,
  ) {
    final declared = <String, String>{...column.arguments};
    // An upload column must say where its files go. `@Image()` on its own is
    // the common case, and the conventional answer — one folder per table —
    // is one the generator can give without the user writing it.
    if (_isUploadKind(column.kind)) {
      declared.putIfAbsent('storagePath', () => "'${schema.table}'");
    }
    final currencyFrom = declared.remove('currencyFrom');
    if (currencyFrom != null) {
      final semantic = declared['semantic']!;
      final prefix = semantic.substring(0, semantic.lastIndexOf(')'));
      declared['semantic'] =
          '$prefix${prefix.endsWith('(') || prefix.trimRight().endsWith(',') ? '' : ','} currencyColumn: ${schema.columnsClass}.${currencyFrom.substring(1)})';
    }
    final String? rules = declared.remove('rules');
    // Non-nullable means required; the rule is derived, never written twice.
    final allowsEmpty =
        column.valueType.startsWith('List<') ||
        column.valueType == 'BeakJsonObject';
    final String required = column.isRequired
        ? (allowsEmpty ? 'BeakRequired(allowEmpty: true)' : 'BeakRequired()')
        : '';
    final String combined = switch ((column.isRequired, rules)) {
      (false, null) => '',
      (false, final String declaredRules) => declaredRules,
      (true, null) => '[$required]',
      (true, final String declaredRules) =>
        declaredRules.startsWith('[')
            ? '[$required, ${declaredRules.substring(1)}'
            : '[$required, ...$declaredRules]',
    };
    return {if (combined.isNotEmpty) 'rules': combined, ...declared};
  }

  static Map<String, String> _relationArgumentsOf(
    BeakRelationIr relation,
    BeakSchemaIr owner,
    BeakSchemaIr related,
  ) => {
    if (relation.kind == BeakRelationKind.belongsToMany) ...{
      'pivotTable': "'${relation.pivotTable ?? pivotTableFor(owner, related)}'",
      'foreignPivotKey':
          "'${relation.foreignPivotKey ?? '${_singular(owner.table)}_id'}'",
      'relatedPivotKey':
          "'${relation.relatedPivotKey ?? '${_singular(related.table)}_id'}'",
    } else
      'foreignKey': "'${relation.foreignKey}'",
    'searchColumnKeys': _searchKeysOf(relation, related),
    ...relation.arguments,
  };

  /// The columns a relationship's picker searches.
  ///
  /// The related model's display column, unless the relationship named
  /// others: a person looks a customer up by email as readily as by name.
  ///
  /// `searchOn` names fields; the stored key each one resolves to is the
  /// related schema's business, so `#firstName` becomes `first_name` here
  /// without the author ever spelling it.
  static String _searchKeysOf(BeakRelationIr relation, BeakSchemaIr related) {
    final keyOf = {
      for (final column in related.columns) column.fieldName: column.columnKey,
    };
    final List<String> keys = relation.searchOn.isEmpty
        ? [related.displayColumnKey]
        : [
            for (final field in relation.searchOn)
              if (keyOf[field] case final String key) key,
          ];
    return '[${keys.map((key) => "'$key'").join(', ')}]';
  }

  /// The mirrored arguments for an inverse relationship.
  static Map<String, String> _inverseArgumentsOf(
    BeakRelationIr relation,
    BeakSchemaIr self,
    BeakSchemaIr owner,
  ) => switch (relation.kind) {
    BeakRelationKind.belongsTo => {
      'foreignKey': "'${relation.foreignKey}'",
      'searchColumnKeys': "['${owner.displayColumnKey}']",
      if (relation.arguments['onDelete'] case final String onDelete)
        'onDelete': onDelete,
    },
    BeakRelationKind.belongsToMany => {
      'pivotTable': "'${relation.pivotTable ?? pivotTableFor(owner, self)}'",
      'foreignPivotKey':
          "'${relation.relatedPivotKey ?? '${_singular(self.table)}_id'}'",
      'relatedPivotKey':
          "'${relation.foreignPivotKey ?? '${_singular(owner.table)}_id'}'",
      'searchColumnKeys': "['${owner.displayColumnKey}']",
    },
    BeakRelationKind.hasOne || BeakRelationKind.hasMany => {
      'foreignKey': "'${relation.foreignKey}'",
      'searchColumnKeys': "['${owner.displayColumnKey}']",
    },
  };

  /// The relationships elsewhere whose inverse belongs on [schema].
  static List<(BeakSchemaIr, BeakRelationIr)> _inversesTargeting(
    BeakSchemaIr schema,
    List<BeakSchemaIr> all,
  ) => [
    for (final owner in all)
      if (owner.className != schema.className)
        for (final relation in owner.relations)
          if (relation.generateInverse &&
              relation.relatedSchema == schema.className)
            (owner, relation),
  ];

  /// The kind the far side of [kind] takes.
  static BeakRelationKind _inverseKindOf(BeakRelationKind kind) =>
      switch (kind) {
        BeakRelationKind.belongsTo => BeakRelationKind.hasMany,
        BeakRelationKind.hasOne ||
        BeakRelationKind.hasMany => BeakRelationKind.belongsTo,
        BeakRelationKind.belongsToMany => BeakRelationKind.belongsToMany,
      };

  /// The field name an inverse relationship takes on the far side.
  static String _inverseNameOf(BeakSchemaIr owner, BeakRelationIr relation) =>
      switch (_inverseKindOf(relation.kind)) {
        BeakRelationKind.belongsTo ||
        BeakRelationKind.hasOne => _camel(_singular(owner.table)),
        _ => _camel(owner.table),
      };

  /// The conventional pivot table joining two schemas: both singular table
  /// names, sorted, joined by an underscore.
  static String pivotTableFor(BeakSchemaIr left, BeakSchemaIr right) {
    final names = [_singular(left.table), _singular(right.table)]..sort();
    return names.join('_');
  }

  static String _singular(String table) {
    if (table.endsWith('ies')) {
      return '${table.substring(0, table.length - 3)}y';
    }
    if (table.endsWith('ses') ||
        table.endsWith('xes') ||
        table.endsWith('ches')) {
      return table.substring(0, table.length - 2);
    }
    return table.endsWith('s') ? table.substring(0, table.length - 1) : table;
  }

  static String _camel(String snake) {
    final parts = snake.split('_');
    return parts.first +
        parts
            .skip(1)
            .map(
              (part) =>
                  part.isEmpty ? '' : part[0].toUpperCase() + part.substring(1),
            )
            .join();
  }

  static void _writeDoc(
    StringBuffer buffer,
    String text, {
    String indent = '',
  }) {
    for (final line in text.split('\n')) {
      buffer.writeln('$indent/// $line');
    }
  }

  static String _fileNameOf(String libraryPath) => libraryPath.split('/').last;

  static String _escape(String value) =>
      value.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
}
