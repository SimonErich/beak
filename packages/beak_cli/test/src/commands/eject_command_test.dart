import 'dart:io';

import 'package:args/command_runner.dart';
import '../../support/beak_cli_internals.dart';
import 'package:test/test.dart';

void main() {
  late Directory root;
  late StringBuffer out;

  setUp(() {
    root = Directory.systemTemp.createTempSync('beak_eject');
    addTearDown(() => root.deleteSync(recursive: true));
    out = StringBuffer();
  });

  Future<int> eject(List<String> args) async =>
      await createBeakRunner(
        BeakCliEnvironment(
          out: out,
          rootDirectory: root,
          now: () => DateTime.utc(2026),
          probe: (host, port) async => false,
        ),
      ).run(['eject', ...args]) ??
      0;

  File file(String path) => File('${root.path}/$path');

  /// Seeds [files] into the project, plus a pubspec naming it.
  void seed(Map<String, String> files) {
    file('pubspec.yaml').writeAsStringSync('name: shop\n');
    for (final MapEntry(key: path, value: contents) in files.entries) {
      file(path)
        ..createSync(recursive: true)
        ..writeAsStringSync(contents);
    }
  }

  const noteSchema = '''
import 'package:beak/beak.dart';
import 'package:beak/schema.dart';

part 'note.beak.dart';

@Resource()
final class Note extends BeakSchema {
  @Display()
  late final String title;
}
''';

  const generatedMain =
      '// GENERATED BY `beak prepare` — DO NOT EDIT.\n'
      "import 'beak/app.g.dart';\n";

  group('an override target', () {
    test('writes a file that compiles and changes nothing', () async {
      expect(await eject(['panel']), 0);

      final String source = file('lib/panel.dart').readAsStringSync();
      expect(source, contains('BeakPanelConfig beakPanel('));
      expect(source, contains('=> defaults;'));
      expect(out.toString(), contains('run `beak prepare`'));
    });

    test('names the symbol discovery looks for, for every target', () async {
      for (final target in BeakEjectTarget.values) {
        if (target.override case final BeakOverrideKind kind) {
          final environment = BeakCliEnvironment(
            out: StringBuffer(),
            rootDirectory: root,
            now: () => DateTime.utc(2026),
            probe: (host, port) async => false,
          );
          await createBeakRunner(
            environment,
          ).run(['eject', target.name, '--force']);

          expect(
            file('lib/${kind.path}').readAsStringSync(),
            contains(kind.symbol),
            reason: '`beak eject ${target.name}` must declare ${kind.symbol}',
          );
        }
      }
    });

    test('refuses to clobber an existing file, and says so', () async {
      file('lib/theme.dart')
        ..createSync(recursive: true)
        ..writeAsStringSync('// mine');

      expect(await eject(['theme']), 1);
      expect(file('lib/theme.dart').readAsStringSync(), '// mine');
      expect(out.toString(), contains('already exists'));
    });

    test('--force replaces it', () async {
      file('lib/theme.dart')
        ..createSync(recursive: true)
        ..writeAsStringSync('// mine');

      expect(await eject(['theme', '--force']), 0);
      expect(
        file('lib/theme.dart').readAsStringSync(),
        contains('OiThemeData'),
      );
    });
  });

  group('eject resource', () {
    test(
      'writes a resource class beside the schema, seeded from beak.yaml',
      () async {
        seed({
          'lib/resources/notes/models/note.dart': noteSchema,
          'beak.yaml': '''
resources:
  notes:
    icon: fileText
    label: Journal
    section: Content
''',
        });

        expect(await eject(['resource', 'notes']), 0);

        final String source = file(
          'lib/resources/notes/note_resource.dart',
        ).readAsStringSync();
        expect(
          source,
          contains('final class NoteResource extends BeakResource'),
        );
        expect(source, contains("import 'models/note.dart';"));
        expect(source, contains('model: const NoteModel()'));
        expect(source, contains('BeakIconToken(OiIcons.fileText)'));
        expect(source, contains("title: 'Journal'"));
        expect(source, contains("navigationGroup: 'Content'"));
        expect(source, isNot(contains('beakResource(')));
        expect(out.toString(), contains('run `beak prepare`'));
      },
    );

    test(
      'imports a schema that lives elsewhere by its relative path',
      () async {
        seed({'lib/models/note.dart': noteSchema});

        expect(await eject(['resource', 'notes']), 0);

        expect(
          file('lib/resources/notes/note_resource.dart').readAsStringSync(),
          contains("import '../../models/note.dart';"),
        );
      },
    );

    test('the class it writes is the one prepare then uses', () async {
      seed({'lib/resources/notes/models/note.dart': noteSchema});
      await eject(['resource', 'notes']);

      final BeakPrepareResult result = runPrepare(
        BeakCliEnvironment(
          out: StringBuffer(),
          rootDirectory: root,
          now: () => DateTime.utc(2026),
          probe: (host, port) async => false,
        ),
      );

      expect(result.isSuccess, isTrue, reason: '${result.discovery.issues}');
      expect(result.discovery.resources.single.className, 'NoteResource');
      expect(result.discovery.resources.single.modelClass, 'NoteModel');
    });

    test('in an authored project, says where to register it', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': 'void main() {}\n',
      });

      expect(await eject(['resource', 'notes']), 0);

      expect(out.toString(), contains('NoteResource()'));
      expect(out.toString(), contains('lib/main.dart'));
      final String source = file(
        'lib/resources/notes/note_resource.dart',
      ).readAsStringSync();
      expect(source, contains('`resources: [...]` list in `lib/main.dart`'));
      expect(source, isNot(contains('`beak prepare` finds this class')));
    });

    test(
      'a hidden table is refused: a resource class is always shown',
      () async {
        seed({
          'lib/resources/notes/models/note.dart': noteSchema,
          'beak.yaml': 'resources:\n  notes:\n    hidden: true\n',
        });

        expect(await eject(['resource', 'notes']), 1);

        expect(out.toString(), contains('hidden: true'));
        expect(out.toString(), contains('resources.notes'));
        expect(
          file('lib/resources/notes/note_resource.dart').existsSync(),
          isFalse,
        );
      },
    );

    test('works for a hand-written model too', () async {
      seed({
        'lib/models/audit.dart': '''
import 'package:beak/beak.dart';

final class AuditModel extends BeakModel {
  const AuditModel();

  @override
  String get table => 'audits';
}
''',
      });

      expect(await eject(['resource', 'audits']), 0);

      final String source = file(
        'lib/resources/audits/audit_resource.dart',
      ).readAsStringSync();
      expect(
        source,
        contains('final class AuditResource extends BeakResource'),
      );
      expect(source, contains("import '../../models/audit.dart';"));
    });

    test('a table no model declares fails, with the near miss', () async {
      seed({'lib/resources/notes/models/note.dart': noteSchema});

      expect(await eject(['resource', 'note']), 1);

      expect(out.toString(), contains('No model declares the table "note"'));
      expect(out.toString(), contains('notes'));
      expect(
        file('lib/resources/note/note_resource.dart').existsSync(),
        isFalse,
      );
    });

    test('a model that already has a class says where it is', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/panel/journal.dart': '''
import 'package:beak/panel.dart';

final class JournalResource extends BeakResource {
  JournalResource() : super(model: const NoteModel());
}
''',
      });

      expect(await eject(['resource', 'notes']), 1);

      expect(out.toString(), contains('JournalResource'));
      expect(out.toString(), contains('lib/panel/journal.dart'));
    });

    test('refuses to clobber an existing file', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/resources/notes/note_resource.dart': '// mine',
      });

      expect(await eject(['resource', 'notes']), 1);
      expect(
        file('lib/resources/notes/note_resource.dart').readAsStringSync(),
        '// mine',
      );
    });

    test('needs a table name', () {
      expect(eject(['resource']), throwsA(isA<UsageException>()));
    });
  });

  group('eject main', () {
    test('rewrites the generated entrypoint as one the project owns', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'beak.yaml': '''
name: Shop
resources:
  notes:
    icon: fileText
    section: Content
''',
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      expect(main, isNot(contains('GENERATED')));
      expect(main, contains('BeakPanel('));
      expect(main, contains("title: 'Shop'"));
      // The default the generated panel showed, spelled out, so switching
      // changes who owns the file and nothing about what the panel shows.
      expect(main, contains('model: NoteModel()'));
      expect(main, contains("navigationGroup: 'Content'"));
      expect(main, contains("import 'resources/notes/models/note.dart';"));
      // Nothing the plain `BeakPanel(resources:)` cannot say, so it says it.
      expect(main, isNot(contains('BeakPanelConfig(')));
      expect(out.toString(), contains('lib/main.dart is yours now'));
    });

    test('keeps applying a panel override to what it spells out', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'lib/panel.dart': EjectCommand.ejectedSource(BeakOverrideKind.panel),
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      expect(main, contains("import 'panel.dart' as panel;"));
      // The generated panel hands its config to `beakPanel`; the authored
      // one has to, or ejecting would silently drop the override.
      expect(main, contains('config: panel.beakPanel('));
      expect(main, contains("title: 'Shop'"));
      expect(main, contains("'BEAK_API_BASE_URL'"));
      expect(main, contains('model: NoteModel()'));
      expect(main, contains('dataSource: dataSource'));
      // Everything in it is constant, so the config is, once: strict lints
      // flag a missing `const` and a redundant inner one alike.
      expect(main, contains('const BeakPanelConfig('));
      expect(main, isNot(contains('const BeakResource(')));
      expect(main, isNot(contains('const String.fromEnvironment')));
    });

    test(
      'lists a hidden model\'s class last, as the generated panel does',
      () async {
        // The generated panel has no default to swap a hidden model's class
        // into, so it appends the class; the sidebar order follows the list.
        seed({
          'lib/resources/notes/models/note.dart': noteSchema,
          'lib/resources/notes/note_resource.dart': '''
import 'package:beak/panel.dart';

import 'models/note.dart';

final class NoteResource extends BeakResource {
  const NoteResource() : super(model: const NoteModel());
}
''',
          'lib/resources/tags/models/tag.dart': noteSchema
              .replaceAll('note.beak.dart', 'tag.beak.dart')
              .replaceAll('class Note ', 'class Tag '),
          'lib/main.dart': generatedMain,
          'beak.yaml': 'resources:\n  notes:\n    hidden: true\n',
        });

        expect(await eject(['main']), 0);

        final String main = file('lib/main.dart').readAsStringSync();
        expect(
          main.indexOf('model: TagModel()'),
          lessThan(main.indexOf('const NoteResource()')),
        );
        expect(main.indexOf('model: TagModel()'), isNonNegative);
      },
    );

    test('marks the config const only when all of it is', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/resources/notes/note_resource.dart': '''
import 'package:beak/panel.dart';

import 'models/note.dart';

final class NoteResource extends BeakResource {
  const NoteResource() : super(model: const NoteModel());
}
''',
        'lib/main.dart': generatedMain,
        'lib/panel.dart': EjectCommand.ejectedSource(BeakOverrideKind.panel),
        'lib/theme.dart': EjectCommand.ejectedSource(BeakOverrideKind.theme),
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      expect(main, isNot(contains('const BeakPanelConfig(')));
      expect(main, contains('BeakPanelConfig('));
      expect(main, contains('theme: theme.beakLightTheme()'));
      expect(main, contains('const NoteResource()'));
      expect(main, contains('const String.fromEnvironment'));
    });

    test('keeps the beak.yaml sidebar settings', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'beak.yaml': '''
theme:
  sidebar:
    collapsible: false
    startCollapsed: true
''',
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      // `BeakPanel(resources:)` has no sidebar parameters; the config does.
      expect(main, contains('config: const BeakPanelConfig('));
      expect(main, contains('sidebarCollapsible: false'));
      expect(main, contains('sidebarDefaultCollapsed: true'));
      expect(main, isNot(contains('beakPanel(')));
    });

    test('lists a resource class instead of the default it replaces', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/resources/notes/note_resource.dart': '''
import 'package:beak/panel.dart';

import 'models/note.dart';

final class NoteResource extends BeakResource {
  const NoteResource() : super(model: const NoteModel());
}
''',
        'lib/main.dart': generatedMain,
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      expect(main, contains('const NoteResource()'));
      expect(main, isNot(contains('model: NoteModel()')));
    });

    test(
      'carries the overrides, screens and origin the generated panel had',
      () async {
        seed({
          'lib/resources/notes/models/note.dart': noteSchema,
          'lib/main.dart': generatedMain,
          'beak.yaml': 'api:\n  baseUrl: auto\n',
          'lib/theme.dart': EjectCommand.ejectedSource(BeakOverrideKind.theme),
          'lib/auth.dart': EjectCommand.ejectedSource(BeakOverrideKind.auth),
          'lib/screens/reports.dart': '''
import 'package:beak/panel.dart';

const BeakScreen reports = BeakScreen(path: '/reports', title: 'Reports');
''',
          // A class for a model this project does not have is still shown.
          'lib/panel/audit_resource.dart': '''
import 'package:beak/panel.dart';

final class AuditResource extends BeakResource {
  AuditResource() : super(model: const AuditModel());
}
''',
        });

        expect(await eject(['main']), 0);

        final String main = file('lib/main.dart').readAsStringSync();
        expect(main, contains("import 'package:flutter/foundation.dart';"));
        expect(main, contains('kIsWeb ? Uri.base.origin'));
        expect(main, contains("import 'theme.dart' as theme;"));
        expect(main, contains('theme: theme.beakLightTheme(),'));
        expect(main, contains('darkTheme: theme.beakDarkTheme(),'));
        expect(main, contains("import 'auth.dart' as auth;"));
        expect(main, contains('auth: auth.beakAuth(),'));
        expect(main, contains("import 'screens/reports.dart';"));
        expect(main, contains('pages: [reports]'));
        expect(main, contains('AuditResource()'));
      },
    );

    test('names a class it cannot match to a model', () async {
      // The generated panel matches by the table the class reports when it
      // runs; a file written once has to decide now, from the source.
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'lib/panel/journal.dart': '''
import 'package:beak/panel.dart';

import '../resources/notes/models/note.dart';

const NoteModel journal = NoteModel();

final class Journal extends BeakResource {
  const Journal() : super(model: journal);
}
''',
      });

      expect(await eject(['main']), 0);

      final String main = file('lib/main.dart').readAsStringSync();
      expect(main, contains('const Journal()'));
      expect(main, contains('model: NoteModel()'));
      final String printed = out.toString();
      expect(printed, contains('Journal (lib/panel/journal.dart)'));
      expect(printed, contains('twice'));
    });

    test('a class matched to its model prints no warning', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'lib/resources/notes/note_resource.dart': '''
import 'package:beak/panel.dart';

import 'models/note.dart';

final class NoteResource extends BeakResource {
  const NoteResource() : super(model: const NoteModel());
}
''',
      });

      expect(await eject(['main']), 0);

      expect(out.toString(), isNot(contains('twice')));
    });

    test('prepare leaves the ejected entrypoint alone', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
      });
      await eject(['main']);
      final String ejected = file('lib/main.dart').readAsStringSync();

      runPrepare(
        BeakCliEnvironment(
          out: StringBuffer(),
          rootDirectory: root,
          now: () => DateTime.utc(2026),
          probe: (host, port) async => false,
        ),
      );

      expect(file('lib/main.dart').readAsStringSync(), ejected);
    });

    test('an entrypoint the project already owns is left alone', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': '// mine\n',
      });

      expect(await eject(['main']), 0);

      expect(file('lib/main.dart').readAsStringSync(), '// mine\n');
      expect(out.toString(), contains('already yours'));
    });

    test('a project that cannot be scanned is not switched', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        'lib/main.dart': generatedMain,
        'lib/dashboard.dart':
            "import 'package:beak/panel.dart';\n"
            'BeakScreen beakDashboard() => throw UnimplementedError();\n',
      });

      expect(await eject(['main']), 1);

      expect(file('lib/main.dart').readAsStringSync(), generatedMain);
      expect(out.toString(), contains('lib/dashboard.dart'));
    });

    test('un-ignores lib/main.dart only, keeping the generated bin/', () {
      const gitignore = '''
# Dart / Flutter
.dart_tool/

# Beak writes these entrypoints and rewrites them on every `beak` command,
# so they are not worth reviewing.
# `beak eject main` hands lib/main.dart over to you, and un-ignores it.
/lib/main.dart
/bin/serve.dart
/bin/migrate.dart

# Secrets
.env
''';

      final String rewritten = EjectCommand.withoutMainIgnore(gitignore);

      expect(rewritten, isNot(contains('/lib/main.dart')));
      // The comment tells the reader to run this very command.
      expect(rewritten, isNot(contains('beak eject main')));
      expect(rewritten, contains('/bin/serve.dart'));
      expect(rewritten, contains('/bin/migrate.dart'));
      expect(rewritten, contains('not worth reviewing.'));
      expect(rewritten, contains('.env'));
      expect(rewritten, isNot(contains('\n\n\n')));
    });

    test('rewrites the project .gitignore', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        '.gitignore': '.dart_tool/\n/lib/main.dart\n/bin/serve.dart\n',
      });

      expect(await eject(['main']), 0);

      final String ignored = file('.gitignore').readAsStringSync();
      expect(ignored, isNot(contains('/lib/main.dart')));
      expect(ignored, contains('/bin/serve.dart'));
      expect(out.toString(), contains('updated .gitignore'));
    });

    test('is idempotent', () async {
      seed({
        'lib/resources/notes/models/note.dart': noteSchema,
        '.gitignore': '.dart_tool/\n',
      });

      expect(await eject(['main']), 0);
      final String first = file('lib/main.dart').readAsStringSync();
      expect(await eject(['main']), 0);

      expect(file('lib/main.dart').readAsStringSync(), first);
      expect(file('.gitignore').readAsStringSync(), '.dart_tool/\n');
      expect(out.toString(), contains('already yours'));
    });
  });

  group('usage', () {
    test('rejects a missing target, listing what is available', () {
      expect(
        eject([]),
        throwsA(
          isA<UsageException>().having(
            (error) => error.message,
            'message',
            allOf(
              contains('lib/theme.dart'),
              contains('resource'),
              isNot(contains('dashboard')),
            ),
          ),
        ),
      );
    });

    test('rejects an unknown target', () {
      expect(eject(['everything']), throwsA(isA<UsageException>()));
    });

    test('the removed dashboard target is unknown', () {
      // A screen at `/` replaces it; there is no override file to write.
      expect(eject(['dashboard']), throwsA(isA<UsageException>()));
    });

    test('a stray argument to a target that takes none is named', () {
      expect(eject(['theme', 'extra']), throwsA(isA<UsageException>()));
    });
  });
}
