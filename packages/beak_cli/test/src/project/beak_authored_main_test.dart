import 'dart:io';

import '../../support/beak_cli_internals.dart';
import 'package:test/test.dart';

/// What a static read of an authored `lib/main.dart` can say about the
/// resources its panel lists, and whether it lists them in a constant
/// context.
void main() {
  late Directory root;

  setUp(() {
    root = Directory.systemTemp.createTempSync('beak_authored_main_');
    addTearDown(() => root.deleteSync(recursive: true));
  });

  /// Writes [source] as `lib/main.dart` and reads it back.
  BeakAuthoredMain? readMain(String source) {
    File('${root.path}/lib/main.dart')
      ..createSync(recursive: true)
      ..writeAsStringSync(source);
    return BeakAuthoredMain.read(root);
  }

  group('what it is', () {
    test('a project without lib/main.dart has no authored entrypoint', () {
      expect(BeakAuthoredMain.read(root), isNull);
    });

    test('a generated entrypoint is not an authored one', () {
      expect(
        readMain(
          "// GENERATED BY `beak prepare` — DO NOT EDIT.\nvoid main() {}",
        ),
        isNull,
      );
    });

    test('an entrypoint with no panel in it says nothing about resources', () {
      final BeakAuthoredMain? main = readMain('void main() {}\n');

      expect(main, isNotNull);
      expect(main!.listedResources, isNull);
      expect(main.resourcesAreConstant, isFalse);
    });
  });

  group('the resources it lists', () {
    test('BeakPanel(resources: [...]) names each class it builds', () {
      final BeakAuthoredMain main = readMain('''
import 'package:beak/panel.dart';

BeakPanel buildPanel() => BeakPanel(
  title: 'Shop',
  resources: [const NoteResource(), TagResource()],
);
''')!;

      expect(main.listedResources, {'NoteResource', 'TagResource'});
      expect(main.resourcesAreConstant, isFalse);
    });

    test('BeakPanelConfig(resources: [...]) counts too', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(
  config: BeakPanelConfig(resources: [NoteResource()]),
);
''')!;

      expect(main.listedResources, {'NoteResource'});
      expect(main.resourcesAreConstant, isFalse);
    });

    test('a class reached through an import prefix is found', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(resources: [notes.NoteResource()]);
''')!;

      expect(main.listedResources, {'NoteResource'});
    });

    test('a default BeakResource is listed as itself', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(
  resources: [const BeakResource(model: NoteModel()), TagResource()],
);
''')!;

      expect(
        main.listedResources,
        containsAll(['BeakResource', 'TagResource']),
      );
    });

    test('a collection if still lists its class', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel(bool admin) => BeakPanel(
  resources: [NoteResource(), if (admin) UserResource()],
);
''')!;

      expect(main.listedResources, {'NoteResource', 'UserResource'});
    });

    test('a spread of a literal list is read through', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(
  resources: [...[NoteResource()], TagResource()],
);
''')!;

      expect(main.listedResources, {'NoteResource', 'TagResource'});
    });

    test('a list built elsewhere cannot be read, so nothing is claimed', () {
      expect(
        readMain(
          'BeakPanel buildPanel() => BeakPanel(resources: all);',
        )!.listedResources,
        isNull,
      );
      expect(
        readMain('''
BeakPanel buildPanel() => BeakPanel(resources: [...others, NoteResource()]);
''')!.listedResources,
        isNull,
      );
    });

    test('every panel in the file is read', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel a() => BeakPanel(resources: [NoteResource()]);
BeakPanel b() => BeakPanel(resources: [TagResource()]);
''')!;

      expect(main.listedResources, {'NoteResource', 'TagResource'});
    });
  });

  group('whether the list is a constant context', () {
    test('const BeakPanelConfig(...) makes every entry constant', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(
  config: const BeakPanelConfig(resources: [NoteResource()]),
);
''')!;

      expect(main.resourcesAreConstant, isTrue);
    });

    test('a const list literal does', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(resources: const [NoteResource()]);
''')!;

      expect(main.resourcesAreConstant, isTrue);
    });

    test('a const variable holding the config does', () {
      final BeakAuthoredMain main = readMain('''
const config = BeakPanelConfig(resources: [NoteResource()]);
''')!;

      expect(main.resourcesAreConstant, isTrue);
    });

    test('a non-constant config around a constant list is not', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel buildPanel() => BeakPanel(
  config: BeakPanelConfig(resources: [NoteResource()]),
);
''')!;

      expect(main.resourcesAreConstant, isFalse);
    });

    test('a const elsewhere in the file changes nothing', () {
      final BeakAuthoredMain main = readMain('''
const title = 'Shop';

BeakPanel buildPanel() => BeakPanel(
  title: title,
  resources: [NoteResource()],
);
''')!;

      expect(main.resourcesAreConstant, isFalse);
    });

    test('every panel must agree', () {
      final BeakAuthoredMain main = readMain('''
BeakPanel a() => BeakPanel(resources: const [NoteResource()]);
BeakPanel b() => BeakPanel(resources: [TagResource()]);
''')!;

      expect(main.resourcesAreConstant, isFalse);
    });
  });
}
